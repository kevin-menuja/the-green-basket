    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
 String username = txtUsername.getText().trim();
    String password = new String(txtPassword.getPassword()).trim();

    // 1️⃣ FIXED MANAGER LOGIN
    if (username.equals("Admin") && password.equals("1010")) {
        JOptionPane.showMessageDialog(this, "Manager Login Successful!");
        ManagerFrame m = new ManagerFrame();
        m.setVisible(true);
        this.dispose();
        return;
    }

    // 2️⃣ CHECK SALES ASSISTANT LOGIN FROM FILE
    boolean loginSuccess = false;

    try (BufferedReader br = new BufferedReader(new FileReader("users.txt"))) {
        String line;

        while ((line = br.readLine()) != null) {
            String[] data = line.split(",");

            String fileUsername = data[0];
            String filePassword = data[1];
            String role = data[2];

            if (username.equals(fileUsername) &&
                password.equals(filePassword) &&
                role.equals("assistant")) {

                JOptionPane.showMessageDialog(this, "Sales Assistant Login Successful!");
                SalesAssistantFrame s = new SalesAssistantFrame();
                s.setVisible(true);
                this.dispose();
                loginSuccess = true;
                break;
            }
        }
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error reading users file!");
    }

    // 3️⃣ INVALID LOGIN
    if (!loginSuccess) {
        JOptionPane.showMessageDialog(this,
            "Invalid Username or Password!",
            "Login Failed",
            JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_btnLoginActionPerformed

